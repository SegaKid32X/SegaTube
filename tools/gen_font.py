#!/usr/bin/env python3
"""Mega Drive tiles for SegaTube's on-screen display (plane A, over the 32X).

Writes a 68000 assembly file with:
  osd_tiles:    tile 0 blank (transparent), then ASCII 32..95 (64 tiles) in a
                shadowed font, then the icons and bar pieces below
  osd_palette:  16 colours (palette line 0)
and a C header with the tile numbers.

usage: gen_font.py OUT.s OUT.h
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from font5x7 import FONT  # noqa: E402

# palette line 0: 0 transparent, 1 shadow, 2 text, 3 dim text, 4 bar fill,
# 5 bar empty, 6 accent (red), 7 panel (dark), 8 highlight (yellow)
PALETTE = [0x000, 0x000, 0xEEE, 0x888, 0x0AE, 0x444, 0x22E, 0x200, 0x0EE,
           0x000, 0x000, 0x000, 0x000, 0x000, 0x000, 0x000]

TEXT, SHADOW, DIM, FILL, EMPTY, RED, PANEL, HIGH = 2, 1, 3, 4, 5, 6, 7, 8


def glyph_tile(rows, fg, bg=0, shadow=True):
    t = [[bg] * 8 for _ in range(8)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                if shadow and y + 1 < 8 and x + 2 < 8 and t[y + 1][x + 2] == bg:
                    t[y + 1][x + 2] = SHADOW
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                t[y][x + 1] = fg
    return t


def icon(rows, fg):
    """8x8 icon from 8 strings of 8."""
    return [[fg if c == "#" else (SHADOW if c == "s" else 0) for c in r] for r in rows]


ICONS = {
    "PLAY":  ["##......", "####....", "######..", "#######.", "######..", "####....", "##......", "........"],
    "PAUSE": ["##..##..", "##..##..", "##..##..", "##..##..", "##..##..", "##..##..", "##..##..", "........"],
    "FF":    ["#...#...", "##..##..", "###.###.", "########", "###.###.", "##..##..", "#...#...", "........"],
    "REW":   ["...#...#", "..##..##", ".###.###", "########", ".###.###", "..##..##", "...#...#", "........"],
    "STOP":  ["........", ".######.", ".######.", ".######.", ".######.", ".######.", ".######.", "........"],
}


def bar(kind):
    t = [[0] * 8 for _ in range(8)]
    for y in range(2, 6):
        for x in range(8):
            t[y][x] = FILL if kind == "fill" else EMPTY
    if kind == "cursor":
        for y in range(0, 8):
            for x in range(3, 5):
                t[y][x] = HIGH
    return t


def panel():
    return [[PANEL] * 8 for _ in range(8)]


def tile_bytes(t):
    out = bytearray()
    for row in t:
        for x in range(0, 8, 2):
            out.append((row[x] & 15) << 4 | (row[x + 1] & 15))
    return out


def main():
    out_s, out_h = sys.argv[1], sys.argv[2]
    tiles = [[[0] * 8 for _ in range(8)]]                 # 0: transparent
    for code in range(32, 96):                              # 1..64: text
        tiles.append(glyph_tile(FONT.get(chr(code), ["....."] * 7), TEXT))
    # (highlighted text: the same tiles in palette line 1, where TEXT is yellow)
    names = {}
    for name, rows in ICONS.items():
        names["T_" + name] = len(tiles)
        tiles.append(icon(rows, TEXT))
    for kind in ("fill", "empty", "cursor"):
        names["T_BAR_" + kind.upper()] = len(tiles)
        tiles.append(bar(kind))
    names["T_PANEL"] = len(tiles)
    tiles.append(panel())

    data = b"".join(tile_bytes(t) for t in tiles)
    with open(out_s, "w") as f:
        f.write("| generated by tools/gen_font.py\n        .section .rodata\n        .balign 2\n")
        f.write("        .global osd_tiles, osd_tiles_end, osd_palette\nosd_tiles:\n")
        for i in range(0, len(data), 16):
            f.write("        .byte " + ",".join(str(b) for b in data[i:i + 16]) + "\n")
        f.write("osd_tiles_end:\nosd_palette:\n")
        f.write("        .word " + ",".join(f"0x{c:03X}" for c in PALETTE) + "\n")
        high = list(PALETTE)
        high[TEXT] = PALETTE[HIGH]
        f.write("        .word " + ",".join(f"0x{c:03X}" for c in high) + "\n")
    with open(out_h, "w") as f:
        f.write("/* generated by tools/gen_font.py */\n#ifndef OSD_TILES_H\n#define OSD_TILES_H\n")
        f.write("#define T_TEXT 1        /* + (ch - 32) */\n#define PAL_HIGH 0x2000 /* palette line 1: the same tiles, yellow */\n")
        for k, v in names.items():
            f.write(f"#define {k} {v}\n")
        f.write(f"#define T_COUNT {len(tiles)}\n#endif\n")


if __name__ == "__main__":
    main()
